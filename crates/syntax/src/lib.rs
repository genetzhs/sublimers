//! Syntax highlighting and themes on top of syntect, with an incremental per-line cache.

use std::path::Path;

use ropey::Rope;
use syntect::highlighting::{HighlightIterator, HighlightState, Highlighter, Style, Theme, ThemeSet};
use syntect::parsing::{ParseState, ScopeStack, SyntaxReference, SyntaxSet};

pub use syntect::highlighting::Color;

/// A colored run within a line, in char offsets relative to the line start.
#[derive(Clone, Debug)]
pub struct Span {
    pub start: usize,
    pub end: usize,
    pub fg: Color,
    pub bold: bool,
    pub italic: bool,
}

/// Color schemes generated by packaging/gen_themes.py, embedded in the binary.
const BUNDLED_THEMES: &[(&str, &str)] = &[
    ("Monokai", include_str!("../themes/Monokai.tmTheme")),
    ("One Dark", include_str!("../themes/One Dark.tmTheme")),
    ("Dracula", include_str!("../themes/Dracula.tmTheme")),
    ("Catppuccin Mocha", include_str!("../themes/Catppuccin Mocha.tmTheme")),
    ("Catppuccin Latte", include_str!("../themes/Catppuccin Latte.tmTheme")),
    ("Nord", include_str!("../themes/Nord.tmTheme")),
    ("Gruvbox Dark", include_str!("../themes/Gruvbox Dark.tmTheme")),
    ("Tokyo Night", include_str!("../themes/Tokyo Night.tmTheme")),
    ("GitHub Light", include_str!("../themes/GitHub Light.tmTheme")),
    ("Mariana", include_str!("../themes/Mariana.tmTheme")),
];

pub struct Syntaxes {
    pub set: SyntaxSet,
    pub themes: ThemeSet,
}

impl Syntaxes {
    /// Built-in syntaxes/themes plus any `.sublime-syntax` / `.tmTheme` files under `user_dir`.
    pub fn load(user_dir: Option<&Path>) -> Self {
        let mut set = SyntaxSet::load_defaults_newlines();
        let mut themes = ThemeSet::load_defaults();
        for (name, xml) in BUNDLED_THEMES {
            if let Ok(t) = ThemeSet::load_from_reader(&mut std::io::Cursor::new(xml.as_bytes())) {
                themes.themes.insert(name.to_string(), t);
            }
        }
        if let Some(dir) = user_dir {
            if dir.join("syntaxes").is_dir() {
                let mut b = set.into_builder();
                let _ = b.add_from_folder(dir.join("syntaxes"), true);
                set = b.build();
            }
            if dir.join("themes").is_dir() {
                let _ = themes.add_from_folder(dir.join("themes"));
            }
        }
        Self { set, themes }
    }

    pub fn theme_names(&self) -> Vec<String> {
        self.themes.themes.keys().cloned().collect()
    }

    pub fn theme(&self, name: &str) -> &Theme {
        self.themes
            .themes
            .get(name)
            .or_else(|| self.themes.themes.get("base16-ocean.dark"))
            .or_else(|| self.themes.themes.values().next())
            .expect("no themes")
    }

    pub fn syntax_names(&self) -> Vec<String> {
        let mut v: Vec<_> = self.set.syntaxes().iter().filter(|s| !s.hidden).map(|s| s.name.clone()).collect();
        v.sort();
        v
    }

    /// Pick a syntax from the file name, then the first line, then a sniff of the content
    /// (so a `.txt` full of shell commands still gets highlighted).
    pub fn detect(&self, path: Option<&Path>, sample: &str) -> &SyntaxReference {
        let plain = self.set.find_syntax_plain_text();
        let first_line = sample.lines().next().unwrap_or("");
        path.and_then(|p| self.set.find_syntax_for_file(p).ok().flatten())
            .filter(|s| s.name != plain.name)
            .or_else(|| self.set.find_syntax_by_first_line(first_line))
            .or_else(|| sniff(sample).and_then(|n| self.set.find_syntax_by_name(n)))
            .unwrap_or(plain)
    }

    pub fn by_name(&self, name: &str) -> Option<&SyntaxReference> {
        self.set.find_syntax_by_name(name)
    }

    /// Line comment prefix for a syntax, from its tmPreferences-ish metadata or a fallback table.
    pub fn comment_prefix(syntax_name: &str) -> &'static str {
        match syntax_name {
            "Python" | "Ruby" | "Bourne Again Shell (bash)" | "Shell-Unix-Generic" | "Perl" | "R" | "YAML" | "Makefile" | "TOML" => "#",
            "SQL" | "Lua" | "Haskell" => "--",
            "Lisp" | "Clojure" => ";",
            "Erlang" | "LaTeX" | "TeX" => "%",
            "Batch File" => "REM",
            _ => "//",
        }
    }
}

/// Highlight cache for one document.
pub struct DocHighlight {
    pub syntax_name: String,
    /// State *before* line i, valid for i < states.len().
    states: Vec<(ParseState, HighlightState)>,
    lines: Vec<Vec<Span>>,
    theme_name: String,
}

impl DocHighlight {
    pub fn new(syntax: &SyntaxReference) -> Self {
        Self { syntax_name: syntax.name.clone(), states: Vec::new(), lines: Vec::new(), theme_name: String::new() }
    }

    pub fn set_syntax(&mut self, syntax: &SyntaxReference) {
        self.syntax_name = syntax.name.clone();
        self.invalidate_from(0);
    }

    pub fn invalidate_from(&mut self, line: usize) {
        self.states.truncate(line + 1);
        self.lines.truncate(line);
    }

    /// Spans for `line`, highlighting forward from the last cached line as needed.
    pub fn line(&mut self, syn: &Syntaxes, theme_name: &str, rope: &Rope, line: usize) -> &[Span] {
        if theme_name != self.theme_name {
            self.theme_name = theme_name.to_string();
            self.invalidate_from(0);
        }
        let theme = syn.theme(theme_name);
        let hl = Highlighter::new(theme);
        let syntax = syn.by_name(&self.syntax_name).unwrap_or_else(|| syn.set.find_syntax_plain_text());
        if self.states.is_empty() {
            self.states.push((ParseState::new(syntax), HighlightState::new(&hl, ScopeStack::new())));
        }
        let line = line.min(rope.len_lines().saturating_sub(1));
        while self.lines.len() <= line {
            let i = self.lines.len();
            let (mut ps, mut hs) = self.states[i].clone();
            let text = rope.line(i).to_string();
            // Avoid pathological cost on minified files.
            let spans = if text.len() > 20_000 {
                vec![Span { start: 0, end: text.chars().count(), fg: theme.settings.foreground.unwrap_or(Color::WHITE), bold: false, italic: false }]
            } else {
                let ops = ps.parse_line(&text, &syn.set).unwrap_or_default();
                let mut out = Vec::new();
                let mut col = 0;
                for (style, piece) in HighlightIterator::new(&mut hs, &ops, &text, &hl) {
                    let n = piece.trim_end_matches('\n').chars().count();
                    if n > 0 {
                        out.push(to_span(style, col, col + n));
                    }
                    col += n;
                }
                out
            };
            self.lines.push(spans);
            self.states.push((ps, hs));
        }
        &self.lines[line]
    }
}

fn to_span(s: Style, start: usize, end: usize) -> Span {
    use syntect::highlighting::FontStyle;
    Span { start, end, fg: s.foreground, bold: s.font_style.contains(FontStyle::BOLD), italic: s.font_style.contains(FontStyle::ITALIC) }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn highlights_rust_incrementally() {
        let syn = Syntaxes::load(None);
        let s = syn.detect(Some(Path::new("a.rs")), "");
        assert_eq!(s.name, "Rust");
        let rope = Rope::from_str("fn main() {\n    let x = \"hi\";\n}\n");
        let mut d = DocHighlight::new(s);
        let spans = d.line(&syn, "base16-ocean.dark", &rope, 1).to_vec();
        assert!(spans.len() > 2);
        assert_eq!(spans.last().unwrap().end, "    let x = \"hi\";".chars().count());
        d.invalidate_from(1);
        assert!(!d.line(&syn, "base16-ocean.dark", &rope, 2).is_empty());
    }

    #[test]
    fn has_themes() {
        let syn = Syntaxes::load(None);
        for (name, _) in BUNDLED_THEMES {
            assert!(syn.themes.themes.contains_key(*name), "missing bundled theme {name}");
        }
        assert!(syn.theme("Dracula").settings.background.is_some());
    }
}

/// Guess a syntax name from content when nothing else matched. Currently: shell scripts / command notes.
fn sniff(sample: &str) -> Option<&'static str> {
    const CMDS: &[&str] = &[
        "apt", "apt-get", "sudo", "cd", "ls", "cp", "mv", "rm", "mkdir", "chmod", "chown", "echo", "export",
        "wget", "curl", "git", "systemctl", "service", "vim", "vi", "nano", "cat", "grep", "tar", "dpkg",
        "yum", "dnf", "ln", "find", "ssh", "scp", "rsync", "docker", "npm", "pip", "make", "source", "for",
        "if", "while", "touch", "useradd", "passwd", "crontab", "mysql", "php", "composer", "certbot", "ufw",
    ];
    let lines: Vec<&str> = sample.lines().map(str::trim).filter(|l| !l.is_empty()).collect();
    if lines.len() < 2 {
        return None;
    }
    let hits = lines.iter().filter(|l| {
        let w = l.trim_start_matches("$ ").split_whitespace().next().unwrap_or("");
        CMDS.contains(&w) || l.starts_with('#') || l.contains(" | ") || l.contains(" && ")
    }).count();
    (hits * 10 >= lines.len() * 4).then_some("Bourne Again Shell (bash)")
}

#[cfg(test)]
mod sniff_tests {
    #[test]
    fn shell_notes_detected() {
        let s = "apt update && apt upgrade -y\nvim .ssh/authorized_keys\n\nwget http://x/y.deb\ndpkg -i y.deb\nsome note";
        assert_eq!(super::sniff(s), Some("Bourne Again Shell (bash)"));
        assert_eq!(super::sniff("Dear John,\nhello there\nregards"), None);
    }
}
